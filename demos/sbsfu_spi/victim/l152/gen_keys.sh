#!/bin/bash
# Generate NUCLEO_L152RE/2_Images_SECoreBin/Src/se_key.s from ST's demo keys.
#
# This is ST's own prebuild step (2_Images_SECoreBin/STM32CubeIDE/prebuild.sh)
# reduced to the one crypto scheme this port uses.  It runs ST's
# prepareimage.py `trans` mode, which emits the key bytes as a sequence of
# instructions rather than as a .byte table -- ST's point being that the key
# never appears as a contiguous constant a memory dump would find.
#
#   ./gen_keys.sh
#
# THE ARCHITECTURE ARGUMENT IS ST'S OWN HERE.  This is a Cortex-M3, so `-v
# V7M` is what every STM32 project in ST's tree passes and what this script
# passes.  The SAM D21 port next door is the one that had to change it: that
# part is ARMv6-M, the V7M output uses MOVW/MOVT, and those do not exist on
# a Cortex-M0+.  Worth stating because the two scripts are otherwise the
# same file and the difference is a single token that fails silently --
# a key that reads back wrong, not a build error.
#
# THESE ARE ST'S PUBLISHED DEMO KEYS, NOT SECRETS.  They ship in the package
# and are the same on every SBSFU demo in the world.  That is correct for this
# rig: the whole point is to recover the AES key by timing, and a recovery is
# only checkable against a key the host already knows.  A product would
# generate its own; nothing here should ever be described as an attack against
# a secret nobody had.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo_root="$(cd "$here/../.." && pwd)"
src="${SBSFU_ROOT:-$(cd "$repo_root/.." && pwd)/sbsfu-src}"

keys="$src/Middlewares/ST/STM32_Secure_Engine/Utilities/KeysAndImages"
binary="$src/Projects/B-L475E-IOT01A/Applications/2_Images_ExtFlash/2_Images_SECoreBin/Binary"
prepareimage="$keys/prepareimage.py"
out="$here/NUCLEO_L152RE/2_Images_SECoreBin/Src/se_key.s"

if [ ! -f "$prepareimage" ]; then
  echo "No SBSFU checkout at $src -- run ./fetch_sbsfu.sh first." >&2
  exit 1
fi

PY=${PYTHON:-python}
CORTEX=V7M
oemkey="$binary/OEM_KEY_COMPANY1_key_AES_CBC.bin"
ecckey="$binary/ECCKEY1.txt"

# Assert the scheme before generating keys for it.  se_crypto_config.h is this
# port's copy; if it ever moves off CBC+ECDSA the key set below is the wrong
# one, and the failure would otherwise be a signature check that never passes.
scheme=$($PY "$prepareimage" conf \
         "$src/Projects/B-L475E-IOT01A/Applications/2_Images_ExtFlash/2_Images_SECoreBin/Inc/se_crypto_config.h")
if [ "$scheme" != "SECBOOT_ECCDSA_WITH_AES128_CBC_SHA256" ]; then
  echo "FAIL: crypto scheme is $scheme, expected SECBOOT_ECCDSA_WITH_AES128_CBC_SHA256" >&2
  exit 1
fi
echo "scheme: $scheme"

{
  echo "/* GENERATED by gen_keys.sh from X-CUBE-SBSFU's demo keys.  Do not edit. */"
  echo "	.section .SE_Key_Data,\"a\",%progbits"
  echo "	.syntax unified"
  echo "	.thumb"
} > "$out"

echo "  SE_ReadKey_1      (AES-128-CBC firmware key)"
$PY "$prepareimage" trans -a GNU -k "$oemkey" -f SE_ReadKey_1 -v $CORTEX >> "$out"

echo "  SE_ReadKey_1_Pub  (ECDSA P-256 public key)"
$PY "$prepareimage" trans -a GNU -k "$ecckey" -f SE_ReadKey_1_Pub -v $CORTEX >> "$out"

echo "	.end" >> "$out"

# The check that matters on a V7M target is the OPPOSITE of the SAM D21's.
# There, an ARMv7-M-only MOVW/MOVT meant the wrong -v had been passed.  Here
# those instructions are legal and expected, so their presence proves
# nothing -- what has to be checked instead is that the two key functions
# were actually emitted.  prepareimage.py exits 0 and writes nothing if it
# cannot read a key file, which would leave an assembler file that builds
# fine and defines no symbols, and the link failure would then name
# SE_ReadKey_1 with no hint as to why.
for sym in SE_ReadKey_1 SE_ReadKey_1_Pub; do
  if ! grep -q "^${sym}:" "$out"; then
    echo "FAIL: $out does not define $sym -- did prepareimage read the keys?" >&2
    exit 1
  fi
done

# prepareimage.py writes CRLF.  This repository is LF in the working tree
# (.gitattributes, because the firmware builds under WSL), and git warns on
# every add otherwise.  Normalise here rather than leaving it for git.
tr -d '\r' < "$out" > "$out.tmp" && mv -f "$out.tmp" "$out"

echo "wrote $out ($(grep -c . "$out") lines)"
