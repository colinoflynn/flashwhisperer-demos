#!/bin/bash
# Show every deviation of this port from stock X-CUBE-SBSFU v2.7.0.
#
#   ./diff_vs_stock.sh              # summary: one line per file
#   ./diff_vs_stock.sh -v           # full unified diffs
#
# The brief for this rig was "as much as possible default/ST-provided".  That
# is only worth anything if it is checkable, and this is the check.
#
# THIS PORT IS THE ONE WHERE THE CHECK IS SHORT, because ST ships a project
# for this exact board: no HAL to write, no BSP to write, no Target/ layer,
# ST's own GCC linker scripts and startup file.  So the port directory holds
# headers with one hunk each, one new source file, two linker maps, and the
# patches below.
#
# TWO THINGS IT NORMALISES, AND WHY NEITHER IS CHEATING
# ------------------------------------------------------
# 1. LINE ENDINGS.  ST ships CRLF; this repository pins LF in the working
#    tree via .gitattributes, because the firmware is built under WSL and
#    `#!/bin/bash\r` is not an interpreter.  Diffing without
#    --strip-trailing-cr reports 100% of lines changed and tells you nothing.
#
# 2. NOTHING ELSE.  No whitespace flags, no comment stripping.  A comment
#    added to ST's source is a change to ST's source and shows up here.
set -uo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo_root="$(cd "$here/../.." && pwd)"
src="${SBSFU_ROOT:-$(cd "$repo_root/.." && pwd)/sbsfu-src}"
stock="$src/Projects/B-L475E-IOT01A/Applications/2_Images_ExtFlash"
se_mw="$src/Middlewares/ST/STM32_Secure_Engine"

verbose=0
[ "${1:-}" = "-v" ] && verbose=1

if [ ! -d "$stock" ]; then
  echo "No SBSFU checkout at $src -- run ../fw_samd21_sbsfu/fetch_sbsfu.sh." >&2
  exit 1
fi

changed=0
new=0
same=0

echo "PORT DIRECTORY -- files this rig keeps its own copy of"
echo

cd "$here/B_L475E_IOT01A"
while IFS= read -r f; do
  rel="${f#./}"
  case "$rel" in
    # New, with no ST counterpart.
    Instr/*) origin="" ;;
    # se_key.s is GENERATED by ./gen_keys.sh, which is ST's own prebuild step.
    2_Images_SECoreBin/Src/se_key.s) origin="" ;;
    # The two linker maps live in ST's Linker_Common/STM32CubeIDE.
    Linker_Common/*) origin="Linker_Common/STM32CubeIDE/$(basename "$rel")" ;;
    # This port's linker script is ST's SBSFU one with sections added.
    2_Images_SBSFU/l475_sbsfu.ld) origin="2_Images_SBSFU/STM32CubeIDE/STM32L475VGTx_FLASH.ld" ;;
    # se_intrinsics.h shadows the MIDDLEWARE's copy, not the project's.
    2_Images_SECoreBin/Inc/se_intrinsics.h) origin="@MW@Core/se_intrinsics.h" ;;
    *) origin="$rel" ;;
  esac

  if [ -z "$origin" ]; then
    echo "  NEW      $rel"
    new=$((new + 1))
    continue
  fi
  case "$origin" in
    @MW@*) orig="$se_mw/${origin#@MW@}" ;;
    *) orig="$stock/$origin" ;;
  esac
  if [ ! -f "$orig" ]; then
    echo "  NEW      $rel  (no $origin in ST's tree)"
    new=$((new + 1))
    continue
  fi
  if diff -q --strip-trailing-cr "$orig" "$rel" >/dev/null 2>&1; then
    echo "  same     $rel"
    same=$((same + 1))
  else
    n=$(diff --strip-trailing-cr "$orig" "$rel" | grep -c '^[<>]')
    echo "  CHANGED  $rel  ($n lines, vs $origin)"
    changed=$((changed + 1))
    if [ "$verbose" = 1 ]; then
      diff -u --strip-trailing-cr "$orig" "$rel" | sed 's/^/      /'
      echo
    fi
  fi
done < <(find . -type f \( -name '*.c' -o -name '*.h' -o -name '*.s' -o -name '*.ld' \) | sort)

echo
echo "PATCHES -- changes to files this rig does NOT keep a copy of"
echo
cd "$here"
for p in patches/*.patch; do
  [ -e "$p" ] || continue
  f=$(grep -m1 '^--- ' "$p" | sed 's/^--- //')
  n=$(grep -c '^[-+][^-+]' "$p")
  echo "  $(basename "$p")"
  echo "      $f, $n changed lines"
  if [ "$verbose" = 1 ]; then
    sed 's/^/      /' "$p"
    echo
  fi
done

echo
echo "$changed changed, $new new, $same byte-identical in the port directory"
echo "$(ls patches/*.patch 2>/dev/null | wc -l) patches against ST's own sources"
echo
echo "Everything else compiled into this firmware is ST's, read out of the"
echo "pinned checkout and never written to: the application layer, the Target"
echo "layer, the Secure Engine, mbedTLS, the HAL, the BSP, the startup file."
