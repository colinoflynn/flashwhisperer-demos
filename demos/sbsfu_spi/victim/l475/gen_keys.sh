#!/bin/bash
# Generate B_L475E_IOT01A/2_Images_SECoreBin/Src/se_key.s from ST's demo keys.
#
# This is ST's own prebuild step reduced to the one crypto scheme this port
# uses: 2_Images_SECoreBin/STM32CubeIDE/prebuild.sh, lines 70-135.  It runs
# ST's prepareimage.py `trans` mode, which emits the key bytes as a sequence
# of instructions rather than as a .byte table -- ST's point being that the
# key never appears as a contiguous constant a memory dump would find.
#
#   ./gen_keys.sh
#
# ONE KEY PAIR PER IMAGE SLOT, which is not optional.  This project is
# configured for two active images (app_sfu.h, SFU_NB_MAX_ACTIVE_IMAGE 2),
# and ST's se_crypto_bootloader.c references SE_ReadKey_2 and
# SE_ReadKey_2_Pub unconditionally as a result.  Emitting only pair 1 links
# everything else and fails on those two symbols -- which is how this script
# was first written.  ST gates each pair on the key file existing, and so
# does the loop below, so a package that ships a third pair gets a third.
#
# `-v V7M` is what every STM32 project in ST's tree passes; this part is a
# Cortex-M4, so the MOVW/MOVT that output uses are legal here.  The SAM D21
# port is the one that had to change it, being ARMv6-M, and that failure is
# silent -- a key that reads back wrong, not a build error.
#
# THESE ARE ST'S PUBLISHED DEMO KEYS, NOT SECRETS.  They ship in the package
# and are the same on every SBSFU demo in the world.  That is correct for
# this rig: the whole point is to recover the AES key by timing, and a
# recovery is only checkable against a key the host already knows.  A
# product would generate its own; nothing here should ever be described as
# an attack against a secret nobody had.
set -euo pipefail

here="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
repo_root="$(cd "$here/../.." && pwd)"
src="${SBSFU_ROOT:-$(cd "$repo_root/.." && pwd)/sbsfu-src}"

keys="$src/Middlewares/ST/STM32_Secure_Engine/Utilities/KeysAndImages"
project="$src/Projects/B-L475E-IOT01A/Applications/2_Images_ExtFlash"
binary="$project/2_Images_SECoreBin/Binary"
prepareimage="$keys/prepareimage.py"
out="$here/B_L475E_IOT01A/2_Images_SECoreBin/Src/se_key.s"

if [ ! -f "$prepareimage" ]; then
  echo "No SBSFU checkout at $src -- run ../fw_samd21_sbsfu/fetch_sbsfu.sh first." >&2
  exit 1
fi

PY=${PYTHON:-python}
CORTEX=V7M

# Assert the scheme before generating keys for it.  This reads ST'S OWN
# se_crypto_config.h -- the port does not override that file -- so if ST's
# shipped scheme for this board were ever not CBC+ECDSA, the key set below
# would be the wrong one and the failure would otherwise show up as a
# signature check that never passes.
scheme=$($PY "$prepareimage" conf "$project/2_Images_SECoreBin/Inc/se_crypto_config.h")
if [ "$scheme" != "SECBOOT_ECCDSA_WITH_AES128_CBC_SHA256" ]; then
  echo "FAIL: crypto scheme is $scheme, expected SECBOOT_ECCDSA_WITH_AES128_CBC_SHA256" >&2
  exit 1
fi
echo "scheme: $scheme"

mkdir -p "$(dirname "$out")"

{
  echo "/* GENERATED by gen_keys.sh from X-CUBE-SBSFU's demo keys.  Do not edit. */"
  echo "	.section .SE_Key_Data,\"a\",%progbits"
  echo "	.syntax unified"
  echo "	.thumb"
} > "$out"

emitted=""
for id in 1 2 3; do
  oemkey="$binary/OEM_KEY_COMPANY${id}_key_AES_CBC.bin"
  if [ -e "$oemkey" ]; then
    echo "  SE_ReadKey_${id}      (AES-128-CBC firmware key $id)"
    $PY "$prepareimage" trans -a GNU -k "$oemkey" -f "SE_ReadKey_${id}" -v $CORTEX >> "$out"
    emitted="$emitted SE_ReadKey_${id}"
  fi
done

for id in 1 2 3; do
  ecckey="$binary/ECCKEY${id}.txt"
  if [ -e "$ecckey" ]; then
    echo "  SE_ReadKey_${id}_Pub  (ECDSA P-256 public key $id)"
    $PY "$prepareimage" trans -a GNU -k "$ecckey" -f "SE_ReadKey_${id}_Pub" -v $CORTEX >> "$out"
    emitted="$emitted SE_ReadKey_${id}_Pub"
  fi
done

echo "	.end" >> "$out"

# prepareimage.py exits 0 and writes nothing if it cannot read a key file,
# which would leave an assembler file that builds fine and defines no
# symbols; the link failure would then name SE_ReadKey_1 with no hint as to
# why.  Check the symbols are there rather than the instructions: MOVW/MOVT
# are legal on this core, so their presence proves nothing.
for sym in $emitted; do
  if ! grep -q "^${sym}:" "$out"; then
    echo "FAIL: $out does not define $sym -- did prepareimage read the key?" >&2
    exit 1
  fi
done
case "$emitted" in
  *SE_ReadKey_1*) ;;
  *) echo "FAIL: no AES key emitted at all -- check $binary" >&2; exit 1 ;;
esac

# prepareimage.py writes CRLF.  This repository is LF in the working tree
# (.gitattributes, because the firmware builds under WSL), and git warns on
# every add otherwise.  Normalise here rather than leaving it for git.
tr -d '\r' < "$out" > "$out.tmp" && mv -f "$out.tmp" "$out"

echo "wrote $out:$emitted"
