"""Generate the victim's 802.15.4 link key as a one-line C header.

    python demos/riot_802154/victim/gen_key.py                  # fresh random
    python demos/riot_802154/victim/gen_key.py --hex <32 hex>   # a given key
    python demos/riot_802154/victim/gen_key.py --riot-default   # drop the header

The key reaches RIOT through `CONFIG_IEEE802154_SEC_DEFAULT_KEY`, which
`sys/include/net/ieee802154_security.h:105` guards with `#if !defined`, so this
needs no edit to RIOT. It is written as a string literal because that is the
shape RIOT's `uint8_t key[] = CONFIG_...` initialiser wants; every byte is
emitted as a `\\xNN` escape so a 0x00, a quote or a backslash in the key cannot
end the literal early or mean something to the shell on the way through make.

**This prints the key.** That is deliberate: the demo's whole claim is that the
key comes back out of the radio timing, and you cannot check that against a key
you never knew. Keep the header out of git -- it is gitignored -- and do not
reuse a key here for anything real.
"""

import argparse
import os
import secrets
import sys

HEADER = """/* Generated by gen_key.py. The victim's 802.15.4 link key.
 *
 * Reaches RIOT as CONFIG_IEEE802154_SEC_DEFAULT_KEY through the Makefile's
 * -include, so no RIOT source is edited. Not in git: see .gitignore.
 */
#ifndef DEMO_KEY_H
#define DEMO_KEY_H

#define DEMO_KEY_STRING "{escaped}"
#define DEMO_KEY_HEX    "{hexed}"

#endif /* DEMO_KEY_H */
"""


def escape(key):
    return "".join("\\x%02x" % b for b in key)


def main():
    here = os.path.dirname(os.path.abspath(__file__))
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--hex", help="use this 128-bit key instead of a fresh one")
    ap.add_argument("--riot-default", action="store_true",
                    help="remove the header, so the build falls back to RIOT's "
                         "own published default key")
    ap.add_argument("--out", default=os.path.join(here, "demo_key.h"))
    args = ap.parse_args()

    if args.riot_default:
        if os.path.exists(args.out):
            os.remove(args.out)
            print("removed %s; the build will use RIOT's own "
                  "\"pizza_margherita\"" % args.out)
        else:
            print("no header to remove; the build already uses RIOT's own key")
        return 0

    if args.hex:
        key = bytes.fromhex(args.hex.strip())
        if len(key) != 16:
            raise SystemExit("--hex wants 32 hex characters, got %d bytes"
                             % len(key))
    else:
        key = secrets.token_bytes(16)

    with open(args.out, "w", newline="\n") as stream:
        stream.write(HEADER.format(escaped=escape(key), hexed=key.hex()))
    print("wrote %s" % args.out)
    print("key  %s" % key.hex())
    print("Write that down. The recovery is checked against it and nothing "
          "else knows it.")
    return 0


if __name__ == "__main__":
    sys.exit(main())
